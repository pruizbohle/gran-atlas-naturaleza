// Immutable production BEFORE renderer for mammal art review. Never boots the game.
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),{execFileSync}=require('node:child_process');
const BASE='f153def213eab6e9b2818abfe7d02174cfdf2c5b';
const source=execFileSync('git',['show',BASE+':www/js/app.js'],{encoding:'utf8',maxBuffer:2e6});
const data=require('../tests/helpers/catalog.cjs').catalogSource(source);
const {SPECIES,SEXUAL_DIMORPHISM}=vm.runInNewContext(data+'\n({SPECIES,SEXUAL_DIMORPHISM})');
const {classifyMammal}=require('../www/js/mammal-art-v3194.js');
const mammals=Object.fromEntries(Object.entries(SPECIES).filter(([id,sp])=>classifyMammal(sp,id)));
const sexes=Object.fromEntries(Object.entries(SEXUAL_DIMORPHISM).filter(([id])=>mammals[id]));
const graphics=source.slice(source.indexOf('function sexSpriteMarkup('),source.indexOf('// initial unlock checks and migration'));
const output=`/* Production reference ${BASE}, v3.19.3. Generated by scripts/mammal-lab-baseline.cjs. Laboratory only. */
(function(root){
'use strict';
const SPECIES=${JSON.stringify(mammals)};
const SEXUAL_DIMORPHISM=${JSON.stringify(sexes)};
${graphics}
root.ATLAS_MAMMAL_LAB={SPECIES,SEXUAL_DIMORPHISM,before:getSpriteMarkup,
 after(id,skin='normal',sex=null){
  return root.ATLAS_DIMORPHISM_LAB.getSpriteMarkup(id,skin,sex);
 },
 previousRenderer(id){
  const sp=SPECIES[id];
  const candidates=[['familyV3154Sprite',()=>familyV3154Sprite(id,'normal')],['unifiedFamilySprite',()=>unifiedFamilySprite(id,'normal')],['africaV310Sprite',()=>africaV310Sprite(id,'normal')],['africaV39Sprite',()=>africaV39Sprite(id,'normal')],['polishedSpeciesSprite',()=>polishedSpeciesSprite(id,'normal')],['asiaV23Sprite',()=>asiaV23Sprite(id,'normal')],['detailedHerpSprite',()=>detailedHerpSprite(id,'normal')],['asiaV22Sprite',()=>asiaV22Sprite(id,'normal')],['asianSpeciesSprite',()=>asianSpeciesSprite(id,'normal')],['premiumSpeciesSprite',()=>premiumSpeciesSprite(sp.name,sp.kind,sp.color,'normal',id)]];
  return (candidates.find(([,fn])=>fn())||['spriteFor: fallback histórico'])[0];
 }};
})(globalThis);
`;
const path='www/js/lab/mammal-sprites-v3193-before.js';
if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8')!==output)throw Error('Stale mammal laboratory baseline');}
else fs.writeFileSync(path,output);
console.log(`${Object.keys(mammals).length} mammals; ${Object.keys(sexes).length} existing sex configurations.`);
