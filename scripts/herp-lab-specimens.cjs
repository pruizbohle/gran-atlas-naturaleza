// Standalone laboratory data, generated from the existing catalog. Never boot app.js.
// node scripts/herp-lab-specimens.cjs [--check]
'use strict';
const fs=require('node:fs');
const {SPECIES}=require('../tests/helpers/sprites.cjs').sprites();
const {classifyHerp}=require('../www/js/herp-art-v3192.js');
const catalog=Object.entries(SPECIES).filter(([,sp])=>classifyHerp(sp)).map(([id,{name,latin,kind,color}])=>({id,name,latin,kind,color}));
// Anatomical references requested for art review; these do not add game species.
const references=[
 ['Rana goliat','Conraua goliath','salamander','#7a855d'],
 ['Rana de uñas africana','Xenopus laevis','salamander','#778b88'],
 ['Rana de lluvia del desierto','Breviceps macrops','salamander','#c0a881'],
 ['Mamba negra','Dendroaspis polylepis','snake','#546766'],
 ['Camaleón de Jackson','Trioceros jacksonii','lizard','#6b9e76'],
 ['Camaleón de Parson','Calumma parsonii','lizard','#719974'],
 ['Geco cola de hoja satánico','Uroplatus phantasticus','lizard','#816b55'],
 ['Varano del Nilo','Varanus niloticus','lizard','#607957']
].map(([name,latin,kind,color])=>({name,latin,kind,color,reference:true}));
const output='/* Generated by scripts/herp-lab-specimens.cjs. Laboratory only. */\nglobalThis.ATLAS_HERP_LAB_SPECIMENS='+JSON.stringify([...catalog,...references],null,2)+';\n';
const path='www/js/lab/herp-specimens-v3192b.js';
if(process.argv.includes('--check')){
 if(fs.readFileSync(path,'utf8')!==output)throw Error('Laboratory specimens out of sync; run node scripts/herp-lab-specimens.cjs');
}else fs.writeFileSync(path,output);
console.log(`${catalog.length} catalog species; ${references.length} laboratory references.`);
