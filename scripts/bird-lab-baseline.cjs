// Reproducible, immutable 3.19.2b renderer for the BEFORE column only.
// This bundle never boots app.js, reads saves, or ships in the game entrypoint.
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),{execFileSync}=require('node:child_process');
const BASE='730d6b89098b3eba63e614d0f623b35666861287';
const source=execFileSync('git',['show',BASE+':www/js/app.js'],{encoding:'utf8',maxBuffer:2e6});
const data=require('../tests/helpers/catalog.cjs').catalogSource(source);
const {SPECIES,SEXUAL_DIMORPHISM}=vm.runInNewContext(data+'\n({SPECIES,SEXUAL_DIMORPHISM})');
const {classifyBird}=require('../www/js/bird-art-v3193.js');
const birds=Object.fromEntries(Object.entries(SPECIES).filter(([,sp])=>classifyBird(sp)));
const sexes=Object.fromEntries(Object.entries(SEXUAL_DIMORPHISM).filter(([id])=>birds[id]));
const graphics=source.slice(source.indexOf('function sexSpriteMarkup('),source.indexOf('// initial unlock checks and migration'));
const output=`/* Frozen production sprites at ${BASE} (3.19.2b). Generated by scripts/bird-lab-baseline.cjs. Laboratory only. */
(function(root){
'use strict';
const SPECIES=${JSON.stringify(birds)};
const SEXUAL_DIMORPHISM=${JSON.stringify(sexes)};
${graphics}
root.ATLAS_BIRD_LAB_BASELINE={SPECIES,SEXUAL_DIMORPHISM,before:getSpriteMarkup,
 after(id,skin='normal',sex=null){
  const validSex=skin==='normal'&&SEXUAL_DIMORPHISM[id]&&(sex==='male'||sex==='female')?sex:null;
  const svg=root.ATLAS_BIRD_ART_V3193(SPECIES[id],applySkin(SPECIES[id].color,skin),skin,validSex);
  return skin==='melanico'?enforceMelanicColors(svg):skin==='albino'?enforcePaleColors(svg):svg;
 }};
})(globalThis);
`;
const path='www/js/lab/bird-sprites-v3192b-before.js';
if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8')!==output)throw Error('Stale bird laboratory baseline');}
else fs.writeFileSync(path,output);
console.log(`${Object.keys(birds).length} birds; ${Object.keys(sexes).length} existing sex configurations; baseline ${BASE}`);
